
#include <iostream>
using namespace std;

int main()
{
    int num1 = 10, num2 = 5;

    int sum = num1 + num2;
    int difference = num1 - num2;
    int multiplication = num1 * num2;

    cout << "Addition = " << sum << endl;
    cout << "Subtraction = " << difference << endl;
    cout << "Multiplication = " << multiplication << endl;

    return 0;
}
